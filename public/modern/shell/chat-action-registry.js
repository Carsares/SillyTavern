import { formatDate, formatNumber } from '../core/utils.js';
import { createChatContextActions } from '../actions/chat-context.js';
import { createChatFileActions } from '../actions/chat-files.js';
import { createChatGenerationActions } from '../actions/chat-generation.js';
import { createChatMessageActions } from '../actions/chat-messages.js';
import { createGroupActions } from '../actions/groups.js';

export function createChatActionRegistry({
    state,
    apiFetch,
    apiFetchResponse,
    loadData,
    render,
    showToast,
    callLegacyBridge,
    subscribeProgress,
    bridgeReload,
    getCharacterAvatarUrl,
}) {
    const chatContextActions = createChatContextActions({
        state,
        apiFetch,
        render,
        showToast,
        getCharacterAvatarUrl,
        reloadChat: bridgeReload.reloadChat,
    });
    const {
        isGroupChatMode,
        ensureAvailableChatMode,
        getChatModeLabel,
        getSelectedChatEntity,
        getChatContextKey,
        getChatEntityName,
        getChatEntityAvatarUrl,
        getGroupAvatarUrl,
        getSelectedChatList,
        getChatId,
        getChatMessageCount,
        getChatUnreadCount,
        getEntityUnreadCount,
        getTotalChatUnreadCount,
        getSelectedChatMessages,
        getChatCacheKey,
        clearChatSearch,
        clearChatTransientState,
        loadChatMessages,
        prepareChatForSelectedContext,
        getCurrentDraftKey,
        getUserName,
        sortChats,
        saveGroupMetadata,
        updateGroupMetadata,
        deleteGroupMetadata,
        updateModernChat,
        updateModernChatMetadata,
        runModernChatFileOperation,
        renameModernChatFile,
        deleteModernChatFile,
        refreshSelectedChatList,
        refreshSelectedChatUnreadState,
        selectLatestUnreadChatTarget,
        createModernChatFile,
        moveChatReadState,
        deleteChatReadState,
        toggleChatSidebar,
        closeChatSidebarForMobileSelection,
        closeChatSidebarOverlay,
    } = chatContextActions;

    const chatFileActions = createChatFileActions({
        state,
        apiFetch,
        apiFetchResponse,
        render,
        showToast,
        formatDate,
        formatNumber,
        getSelectedChatEntity,
        getChatContextKey,
        getChatEntityName,
        isGroupChatMode,
        getSelectedChatList,
        getChatId,
        getChatCacheKey,
        getUserName,
        sortChats,
        clearChatSearch,
        loadChatMessages,
        refreshSelectedChatList,
        createModernChatFile,
        updateGroupMetadata,
        moveChatReadState,
        deleteChatReadState,
        renameModernChatFile,
        deleteModernChatFile,
    });
    const { closeChatBackups } = chatFileActions;

    const chatMessageActions = createChatMessageActions({
        state,
        render,
        showToast,
        getSelectedChatEntity,
        getChatContextKey,
        getSelectedChatMessages,
        getCurrentDraftKey,
        getChatCacheKey,
        isGroupChatMode,
        updateModernChat,
        refreshSelectedChatList,
        reloadChat: bridgeReload.reloadChat,
    });

    const chatGenerationActions = createChatGenerationActions({
        state,
        render,
        showToast,
        callLegacyBridge,
        subscribeProgress,
        formatNumber,
        getSelectedChatEntity,
        getChatContextKey,
        getChatEntityName,
        isGroupChatMode,
        getSelectedChatMessages,
        getCurrentDraftKey,
        getChatCacheKey,
        getUserName,
        loadChatMessages,
        refreshSelectedChatList,
        createModernChatFile,
        runModernChatFileOperation,
        waitForEngineSync: bridgeReload.waitForPendingReloads,
        // 开场白在未对话的聊天里本地切换 / 载入备用开场白：改消息、保存并登记 reloadChat
        updateModernChatAndSync: chatContextActions.updateModernChatAndSync,
    });

    const groupActions = createGroupActions({
        state,
        apiFetch,
        loadData,
        render,
        showToast,
        ensureAvailableChatMode,
        updateGroupMetadata,
        deleteGroupMetadata,
    });
    const { beginGroupCreate } = groupActions;

    return {
        chatContextActions,
        chatFileActions,
        chatGenerationActions,
        chatMessageActions,
        groupActions,
        beginGroupCreate,
        clearChatSearch,
        clearChatTransientState,
        closeChatBackups,
        closeChatSidebarForMobileSelection,
        closeChatSidebarOverlay,
        createModernChatFile,
        ensureAvailableChatMode,
        getChatContextKey,
        getChatEntityAvatarUrl,
        getChatEntityName,
        getChatId,
        getChatMessageCount,
        getChatUnreadCount,
        getEntityUnreadCount,
        getTotalChatUnreadCount,
        getChatModeLabel,
        getGroupAvatarUrl,
        getSelectedChatEntity,
        getSelectedChatList,
        isGroupChatMode,
        loadChatMessages,
        prepareChatForSelectedContext,
        refreshSelectedChatList,
        refreshSelectedChatUnreadState,
        selectLatestUnreadChatTarget,
        saveGroupMetadata,
        updateGroupMetadata,
        updateModernChatMetadata,
        sortChats,
        toggleChatSidebar,
    };
}
