import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { startFixture, IMAGE_BASE64 } from './fixture.mjs';

test('image job HTTP recovery and cancellation never repeat the chargeable submission', async t => {
    const requests = [];
    let failPoll = true;
    const peer = http.createServer((req, res) => {
        requests.push([req.method, req.url]);
        req.resume();
        if (req.method === 'POST') res.writeHead(200, { 'content-type': 'application/json' }).end('{"id":"existing-job"}');
        else if (req.method === 'DELETE') res.writeHead(200, { 'content-type': 'application/json' }).end('{}');
        else if (failPoll) res.writeHead(503).end();
        else res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify({ done: true, generations: [{ img: IMAGE_BASE64 }] }));
    });
    await new Promise(resolve => peer.listen(0, '127.0.0.1', resolve));
    t.after(async () => { peer.closeAllConnections(); await new Promise(resolve => peer.close(resolve)); });
    const app = await startFixture(); t.after(() => app.close());
    const image = await app.api('/resources', { kind: 'connection', name: 'Local Horde', data: { ...app.connectionData, provider: 'horde', type: 'image', model: 'local-image', baseUrl: `http://127.0.0.1:${peer.address().port}/api/v2`, maxPolls: 1, pollIntervalMs: 0 } });
    assert.equal(image.status, 201);
    const configured = await app.api(`/conversations/${app.conversation.id}/commands`, { type: 'conversation.configure', expectedContentRevision: 0, settings: { connectionId: app.connection.id, imageConnectionId: image.value.id, tools: ['generate_image'], memoryFrequency: 1000 } });
    assert.equal(configured.status, 200);
    const accepted = await app.send('USE_IMAGE');
    assert.equal(accepted.status, 202);
    const stopped = await app.wait(accepted.value.turnId);
    assert.equal(stopped.status, 'failed');
    const jobs = (await app.api(`/conversations/${app.conversation.id}/jobs`)).value;
    const job = jobs.find(item => item.kind === 'provider-request');
    assert.equal(job.payload.jobId, 'existing-job');
    const path = `/conversations/${app.conversation.id}/jobs/${job.id}`;
    const canceled = await app.api(`${path}/cancel`, {});
    assert.equal(canceled.status, 200, JSON.stringify(canceled.value));
    assert.equal(canceled.value.payload.state, 'cancel-requested');
    await app.api(`${path}/cancel`, {});
    assert.equal(requests.filter(([method]) => method === 'DELETE').length, 1);
    failPoll = false;
    const recovered = await app.api(`${path}/resume`, {});
    assert.equal(recovered.status, 200, JSON.stringify(recovered.value));
    const media = recovered.value.payload.result.media[0];
    assert.ok(media.attachmentId);
    const file = await fetch(`${app.url}/api/conversation/v1/attachments/${media.attachmentId}`);
    assert.equal(file.status, 200);
    assert.ok((await file.arrayBuffer()).byteLength > 0);
    const before = requests.length;
    assert.equal((await app.api(`${path}/resume`, {})).status, 200);
    assert.equal(requests.length, before);
    assert.equal(requests.filter(([method]) => method === 'POST').length, 1);
    assert.equal(app.application.services.store.getTurn(stopped.id).status, 'failed');
    assert.equal(app.application.services.store.getTool(job.dependencies.origin).status, 'completed');
    assert.equal((await app.snapshot()).messages.some(item => item.media?.some(part => part.attachmentId === media.attachmentId)), false);
});
